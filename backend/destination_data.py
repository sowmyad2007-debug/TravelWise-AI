def normalize_place_name(name: str) -> str:
    """
    Normalizes attraction names for reliable duplicate detection.
    Strips noise words, punctuation, and returns sorted unique tokens.
    Preserves text inside parentheses as separate tokens.
    """
    if not name:
        return ""
    s = name.lower().strip()
    s = s.replace('(', ' ').replace(')', ' ').replace('[', ' ').replace(']', ' ')
    s = re.sub(r'\b(visit|explore|tour|trip|viewpoint|view|scenic|walk|stroll|highlights?|the|and|&|point|hub|center|centre|monument|attraction|stop|unesco)\b', ' ', s)
    s = re.sub(r'[^a-z0-9]', ' ', s)
    tokens = [t for t in s.split() if len(t) > 2]
    return " ".join(sorted(set(tokens)))

def are_places_duplicate(
    name1: str,
    name2: str,
    coord1: Optional[Tuple[float, float]] = None,
    coord2: Optional[Tuple[float, float]] = None,
    place_id1: Optional[str] = None,
    place_id2: Optional[str] = None
) -> bool:
    """
    Determines if two place entries refer to the same physical attraction.
    Checks:
    1. Exact place_id match (if both available, different IDs indicate distinct attractions)
    2. Exact normalized name match
    3. Token subset matching (e.g. 'Fort Aguada' vs 'Fort Aguada & Lighthouse')
    4. Jaccard similarity >= 0.50
    5. Geographic proximity (< 250m) when name tokens share common keywords
    """
    if place_id1 and place_id2:
        return place_id1 == place_id2

    norm1 = normalize_place_name(name1)
    norm2 = normalize_place_name(name2)
    if not norm1 or not norm2:
        return False
    if norm1 == norm2:
        return True

    t1 = set(norm1.split())
    t2 = set(norm2.split())
    if not t1 or not t2:
        return False

    # Subset match (e.g., shorter name is completely contained in longer name)
    if t1.issubset(t2) or t2.issubset(t1):
        if len(t1.intersection(t2)) >= min(len(t1), len(t2)):
            return True

    # Jaccard overlap
    jaccard = len(t1.intersection(t2)) / len(t1.union(t2))
    if jaccard >= 0.50:
        return True

    # Geographic proximity check
    if coord1 and coord2 and coord1[0] is not None and coord2[0] is not None:
        lat_diff = abs(coord1[0] - coord2[0])
        lon_diff = abs(coord1[1] - coord2[1])
        # Identical map coordinate pin (< 20 meters)
        if lat_diff < 0.0002 and lon_diff < 0.0002:
            return True
        # Close proximity (< 250 meters) with at least 1 overlapping meaningful keyword
        if lat_diff < 0.0025 and lon_diff < 0.0025 and len(t1.intersection(t2)) >= 1:
            return True

    return False

