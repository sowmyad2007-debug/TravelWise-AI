def get_destination_weather(destination_name: str, lat: float = None, lon: float = None):
    """
    Fetches real-world weather from Open-Meteo API with in-memory caching and offline fallback.
    """
    dest_info = get_destination_info(destination_name)
    latitude = lat or dest_info.get('latitude', 17.3850)
    longitude = lon or dest_info.get('longitude', 78.4867)

    cache_key = f"{round(latitude, 3)},{round(longitude, 3)}"
    now = time.time()

    if cache_key in WEATHER_CACHE:
        cached = WEATHER_CACHE[cache_key]
        if now - cached['timestamp'] < CACHE_TTL_SECONDS:
            return cached['data']

    url = f"https://api.open-meteo.com/v1/forecast?latitude={latitude}&longitude={longitude}&current=temperature_2m,relative_humidity_2m,weather_code,wind_speed_10m"
    try:
        resp = requests.get(url, timeout=2.5)
        if resp.status_code == 200:
            current = resp.json().get('current', {})
            code = current.get('weather_code', 0)
            code_meta = WEATHER_CODE_MAP.get(code, ("Clear / Fair", "Fair", "⛅", False))
            
            result = {
                "temperature_c": round(current.get('temperature_2m', 20.0), 1),
                "humidity_pct": current.get('relative_humidity_2m', 60),
                "condition": code_meta[0],
                "description": code_meta[1],
                "icon": code_meta[2],
                "is_raining": code_meta[3],
                "has_precipitation_risk": code_meta[3],
                "wind_speed_kmh": round(current.get('wind_speed_10m', 5.0), 1),
                "source": "Live Open-Meteo Satellite Feed",
                "retrieved_at": datetime.now().strftime("%Y-%m-%d %H:%M:%S")
            }
            WEATHER_CACHE[cache_key] = {"data": result, "timestamp": now}
            return result
    except Exception:
        pass

    fallback = {
        "temperature_c": 22.0,
        "humidity_pct": 60,
        "condition": "Seasonal Average",
        "description": dest_info.get('seasonal_climate', "Pleasant seasonal conditions."),
        "icon": "🌤️",
        "is_raining": False,
        "has_precipitation_risk": False,
        "wind_speed_kmh": 6.0,
        "source": "Verified Seasonal Historical Benchmark (Offline Mode)",
        "retrieved_at": datetime.now().strftime("%Y-%m-%d %H:%M:%S")
    }
    return fallback

def calculate_preference_match_score(activity: dict, user_interests: list, travel_style: str = "balanced", remaining_budget: float = 5000, weather_is_raining: bool = False):
    """
    Transparent Multi-Factor Scoring Engine:
    Score = 0.40 * Interest_Alignment + 0.30 * Budget_Fit + 0.20 * Weather_Safety + 0.10 * Time_Efficiency
    Guaranteed to return an integer between 0 and 100.
    """
    act_interests = set(activity.get('interests', []))
    user_set = set(user_interests or [])
    if act_interests and user_set:
        overlap = len(act_interests.intersection(user_set))
        interest_score = min(100, int((overlap / len(act_interests)) * 100))
    else:
        interest_score = 75

    cost = activity.get('estimated_entry_cost', 0) + activity.get('estimated_transport_cost', 50)
    if cost == 0:
        budget_score = 100
    elif cost <= 200:
        budget_score = 90
    elif cost <= 500:
        budget_score = 80 if travel_style != "budget" else 60
    elif cost > 1000:
        budget_score = 50 if travel_style == "budget" else 75
    else:
        budget_score = 70

    is_indoor = activity.get('indoor', False) or activity.get('weather_suitability') == 'indoor_only'
    if weather_is_raining:
        weather_score = 98 if is_indoor else 40
    else:
        weather_score = 95 if activity.get('weather_suitability') != 'indoor_only' else 85

    transit = activity.get('transit_time_mins', 20)
    time_score = 95 if transit <= 20 else (80 if transit <= 35 else 65)

    total = int(round(0.40 * interest_score + 0.30 * budget_score + 0.20 * weather_score + 0.10 * time_score))
    # Guarantee strictly within [0, 100]
    total = max(0, min(100, total))

    components = {
        "interest_alignment": interest_score,
        "budget_fit": budget_score,
        "weather_safety": weather_score,
        "time_efficiency": time_score,
        "weights": "40% Interests • 30% Cost • 20% Weather • 10% Transit Time",
        "explanation": f"Scored {total}% based on interest overlap ({interest_score}%), cost tier ({budget_score}%), and weather viability ({weather_score}%)."
    }

    return total, components

