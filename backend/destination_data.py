def get_destination_info(destination_name: str, interests: list = None, travel_style: str = "balanced"):
    """
    Intelligently resolves destination information from verified knowledge catalog.
    1. Checks canonical alias mapping (handling variations, alternate names, state/country tokens).
    2. Checks exact destination keys.
    3. Checks title and display name matches.
    4. Falls back gracefully to structured generic estimate without fake places.
    """
    if not destination_name:
        return generate_generic_destination("Destination", interests or [], travel_style)

    raw_key = destination_name.strip().lower()

    # 1. Check canonical alias helper
    canonical_key = resolve_canonical_key(raw_key)
    if canonical_key and canonical_key in DESTINATIONS:
        return DESTINATIONS[canonical_key]

    # 2. Check direct key match
    if raw_key in DESTINATIONS:
        return DESTINATIONS[raw_key]

    # 3. Check direct in alias dict
    if raw_key in DESTINATION_ALIASES:
        target = DESTINATION_ALIASES[raw_key]
        if target in DESTINATIONS:
            return DESTINATIONS[target]

    # 4. Check display names
    for dest_key, data in DESTINATIONS.items():
        if data.get("name", "").strip().lower() == raw_key:
            return data

    # 5. Check substring/token match with min length >= 4 to avoid short false positives
    for dest_key, data in DESTINATIONS.items():
        if len(dest_key) >= 4 and (dest_key in raw_key or raw_key in dest_key):
            return data

    return generate_generic_destination(destination_name, interests or [], travel_style)
